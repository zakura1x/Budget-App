"""
The go / no-go number for ARCHITECTURE.md section 5.7 - run it WHERE THE APP RUNS.

    python scripts/benchmark_fetch.py            # on the IIS server, in the app folder

Estimates the cold load of 10,000 transactions (fetch + decrypt + parse) from
the machine it runs on. READ-ONLY: the rows are generated by the server inside
the query (CRYPT_GEN_RANDOM), so nothing is written and no real data is read.

Why this exists: on 2026-09-11 the benchmark in tests/test_crypto_performance.py
measured 2.35 s from the development PC - over the 1.5 s line - and diagnosis
showed almost all of it was the internet link between that PC and the database
(14 ms round trip, ~12 Mbit/s): 10,000 bare ids came back in 39 ms, the same
rows with 250-byte payloads in ~1.75 s. Production runs next to the database,
where that link is not the constraint. The 1.5 s rule applies to THIS number,
measured there.
"""

import os
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)

ROWS = 10_000
PAYLOAD_BYTES = 262  # measured size of a realistic sealed transaction payload
THRESHOLD_MS = 1500


def main() -> int:
    import random

    from sqlalchemy import text
    from sqlalchemy.pool import NullPool

    from app.core.crypto.dek import generate_dek
    from app.core.crypto.user_cipher import UserCipher
    from app.db.connection import create_db_engine

    engine = create_db_engine(poolclass=NullPool)
    generate = (
        f"SELECT TOP ({ROWS}) CAST(ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS BIGINT), "
        f"CAST(CRYPT_GEN_RANDOM({PAYLOAD_BYTES}) AS VARBINARY(MAX)) "
        "FROM sys.all_objects a CROSS JOIN sys.all_objects b"
    )

    with engine.connect() as conn:
        rtt = []
        for _ in range(10):
            t0 = time.perf_counter()
            conn.execute(text("SELECT 1")).scalar()
            rtt.append((time.perf_counter() - t0) * 1000)
        fetch = []
        for _ in range(3):
            t0 = time.perf_counter()
            conn.execute(text(generate)).fetchall()
            fetch.append((time.perf_counter() - t0) * 1000)
    engine.dispose()

    # Decrypt + parse of 10,000 realistic payloads, on this machine's CPU.
    cipher = UserCipher(1, generate_dek(), 1)
    rng = random.Random(1)
    sealed = [
        (i, cipher.seal("transactions", i, {
            "txn_date": "2026-09-08", "type": "expense", "amount": f"{rng.randint(20, 5000)}.00",
            "account_id": 3, "merchant": "SM Supermarket", "notes": "weekly run",
            "splits": [{"category_id": 11, "amount": "100.00", "note": None}],
            "tag_ids": [], "recurring_id": None, "attachment_id": None,
        }))
        for i in range(1, ROWS + 1)
    ]
    t0 = time.perf_counter()
    for row_id, blob in sealed:
        cipher.open("transactions", row_id, blob, 1)
    decrypt_ms = (time.perf_counter() - t0) * 1000

    fetch_ms = statistics.median(fetch)
    total = fetch_ms + decrypt_ms
    print(f"round trip to the database : {statistics.median(rtt):.1f} ms")
    print(f"fetch {ROWS} x {PAYLOAD_BYTES}-byte rows : {fetch_ms:.0f} ms")
    print(f"decrypt + parse            : {decrypt_ms:.0f} ms")
    print(f"ESTIMATED COLD LOAD        : {total:.0f} ms   (line: {THRESHOLD_MS} ms)")
    if total > THRESHOLD_MS:
        print("-> Over the line. Adopt the bucket-column plan (ARCHITECTURE.md 5.7).")
        return 1
    print("-> Under the line. Full-row encryption stands; no bucket columns needed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
